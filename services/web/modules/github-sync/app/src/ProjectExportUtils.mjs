// @ts-check

import crypto from 'node:crypto'

/**
 * Turn an archive entry name into a safe relative path, or null when the entry
 * must be skipped (absolute paths, drive letters, `..` traversal).
 *
 * @param {string} entryName
 * @returns {string|null}
 */
export function safeRelativePath(entryName) {
  const normalized = entryName.replace(/\\/g, '/')
  if (normalized.startsWith('/') || /^[A-Za-z]:/.test(normalized)) return null
  const segments = normalized.split('/')
  if (segments.some(segment => segment === '..' || segment === '')) return null
  return normalized
}

/**
 * Build artifacts are excluded by default: they are regenerated by every
 * compile and would otherwise bloat the mirror and produce noisy diffs.
 *
 * @param {string} relativePath
 * @param {string[]} excludedPatterns regular expressions matched on the basename
 * @returns {boolean}
 */
export function isExcluded(relativePath, excludedPatterns) {
  if (relativePath === '.git' || relativePath.startsWith('.git/')) return true
  const baseName = relativePath.split('/').pop() || ''
  return excludedPatterns.some(pattern => new RegExp(pattern).test(baseName))
}

/**
 * Stable digest of an exported project tree. Used both to skip unchanged
 * projects and to decide whether the mirror needs a commit at all.
 *
 * @param {Array<{ path: string, sha256: string }>} files
 * @returns {string}
 */
export function contentHash(files) {
  const hash = crypto.createHash('sha256')
  for (const file of files) {
    hash.update(file.path)
    hash.update('\0')
    hash.update(file.sha256)
    hash.update('\n')
  }
  return hash.digest('hex')
}

/**
 * Directory name for a project: `<id>-<slug>`. The slug is only cosmetic; the
 * id keeps it unique even when two projects share a name.
 *
 * @param {string} name
 * @returns {string}
 */
export function slugify(name) {
  return (
    String(name || 'project')
      .toLowerCase()
      .normalize('NFKD')
      .replace(/[^a-z0-9]+/g, '-')
      .replace(/^-+|-+$/g, '')
      .slice(0, 60) || 'project'
  )
}

export default { safeRelativePath, isExcluded, contentHash, slugify }
